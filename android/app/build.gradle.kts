// Release signing comes from keystore/keystore.properties (created by scripts/build-android.sh on first build).
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore/keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

android {
    namespace = "tools.lars.wgo"
    compileSdk = 35

    defaultConfig {
        applicationId = providers.gradleProperty("wgo.applicationId").get()
        minSdk = 26
        targetSdk = 35
        versionCode = providers.gradleProperty("wgo.versionCode").get().toInt()
        versionName = providers.gradleProperty("wgo.versionName").get()
        // plain HTTP is only for the local dev server (backend/dev/server.mts): debug builds, or -Pwgo.cleartext=true
        manifestPlaceholders["cleartext"] = providers.gradleProperty("wgo.cleartext").getOrElse("false")
    }

    signingConfigs {
        if (keystoreProps.isNotEmpty()) {
            create("release") {
                storeFile = rootProject.file("keystore/" + keystoreProps.getProperty("storeFile"))
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        debug {
            manifestPlaceholders["cleartext"] = "true"
        }
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.findByName("release") ?: signingConfigs.getByName("debug")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions { jvmTarget = "17" }
    buildFeatures {
        compose = true
        buildConfig = true
    }
    packaging { resources.excludes += "/META-INF/{AL2.0,LGPL2.1}" }
}

